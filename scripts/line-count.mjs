/** Parse `git ls-files -s -z` into one entry per tracked path. */
function listTrackedFiles(repoRoot) {
  const raw = execFileSync('git', ['ls-files', '-s', '-z'], {
    cwd: repoRoot,
    windowsHide: true,
    maxBuffer: 512 * 1024 * 1024,
  });
  const seen = new Map();
  let start = 0;
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] !== 0) continue;
    const record = raw.toString('utf8', start, i);
    start = i + 1;
    if (!record) continue;
    const tab = record.indexOf('\t');
    if (tab === -1) continue;
    const meta = record.slice(0, tab).split(' ');
    const file = record.slice(tab + 1);
    // Merge-conflict stages repeat a path; count it once.
    if (!seen.has(file)) seen.set(file, { mode: meta[0], oid: meta[1], path: file });
  }
  return [...seen.values()];
}

/** Which reported scope a file belongs to. */
function scopeOf(file) {
  for (const upstream of UPSTREAM_PREFIXES) {
    if (file.startsWith(upstream.prefix)) return upstream.prefix;
  }
  return '';
}

/**
 * Read and classify every tracked file.
 * Returns counted rows per scope, excluded rows, and the per-file records the
 * blame pass needs.
 */
function collect(repoRoot, entries) {
  /** @type {Map<string, {scope:string, category:string, kind:string, files:number, lines:number, nonBlank:number}>} */
  const rows = new Map();
  /** @type {Map<string, {scope:string, area:string, files:number, lines:number, nonBlank:number}>} */
  const areas = new Map();
  /** @type {Map<string, {reason:string, files:number, lines:number, nonBlank:number, linesKnown:boolean, examples:string[]}>} */
  const excluded = new Map();
  /** @type {{path:string, scope:string, lines:number}[]} */
  const counted = [];
  const uncategorizedPaths = [];

  const addRow = (scope, category, kind, lines, nonBlank) => {
    const key = `${scope}\u0000${category}\u0000${kind}`;
    let row = rows.get(key);
    if (!row) {
      row = { scope, category, kind, files: 0, lines: 0, nonBlank: 0 };
      rows.set(key, row);
    }
    row.files += 1;
    row.lines += lines;
    row.nonBlank += nonBlank;
  };

  const addArea = (scope, area, lines, nonBlank) => {
    const key = `${scope}\u0000${area}`;
    let row = areas.get(key);
    if (!row) {
      row = { scope, area, files: 0, lines: 0, nonBlank: 0 };
      areas.set(key, row);
    }
    row.files += 1;
    row.lines += lines;
    row.nonBlank += nonBlank;
  };

  const addExcluded = (reason, file, linesKnown, lines, nonBlank) => {
    let row = excluded.get(reason);
    if (!row) {
      row = { reason, files: 0, lines: 0, nonBlank: 0, linesKnown, examples: [] };
      excluded.set(reason, row);
    }
    row.files += 1;
    if (linesKnown) {
      row.lines += lines;
      row.nonBlank += nonBlank;
    } else {
      row.linesKnown = false;
    }
    if (row.examples.length < 3) row.examples.push(file);
  };

  for (const entry of entries) {
    const file = entry.path;

    // Gitlinks (submodules) and symlinks hold no lines of this repository's code.
    if (entry.mode === '160000') {
      addExcluded('Submodule reference (gitlink)', file, false, 0, 0);
      continue;
    }
    if (entry.mode === '120000') {
      addExcluded('Symbolic link', file, false, 0, 0);
      continue;
    }

    const vendored = excludedSegment(file);
    const basename = file.slice(file.lastIndexOf('/') + 1);
    const ext = extensionOf(basename);

    if (BINARY_EXTENSIONS.has(ext)) {
      addExcluded('Binary file (not text)', file, false, 0, 0);
      continue;
    }

    let buffer;
    try {
      buffer = readFileSync(path.join(repoRoot, file));
    } catch (err) {
      if (err && (err.code === 'ENOENT' || err.code === 'EISDIR')) {
        // Tracked but absent from the working tree (sparse checkout, or a
        // submodule whose contents were never initialised). Reported, not dropped.
        addExcluded('Tracked but missing from the working tree', file, false, 0, 0);
        continue;
      }
      throw err;
    }

    if (buffer.subarray(0, 8000).includes(0)) {
      addExcluded('Binary file (not text)', file, false, 0, 0);
      continue;
    }

    const text = buffer.toString('utf8');
    const { lines, nonBlank } = countLines(text);

    if (vendored) {
      addExcluded(`Vendored or build-output path (\`${vendored}/\`)`, file, true, lines, nonBlank);
      continue;
    }

    const scope = scopeOf(file);
    const { category: extCategory, kind } = kindOf(file);
    const category = categoryOf(file, extCategory, declaresGenerated(text));

    addRow(scope, category, kind, lines, nonBlank);
    addArea(scope, areaOf(file, scope), lines, nonBlank);
    counted.push({ path: file, scope, lines });
    if (category === 'Uncategorized') uncategorizedPaths.push(file);
  }

  return { rows: [...rows.values()], areas: [...areas.values()], excluded: [...excluded.values()], counted, uncategorizedPaths };
}

