const HELP = `line-count.mjs — count the lines of this repository, by category and by authorship.

Usage:
  node ${SCRIPT_REL_FALLBACK} [options]

Options:
  --json                  Emit JSON instead of a Markdown table.
  --markdown              Emit the Markdown table (default).
  --blame                 Attribute every surviving line with \`git blame\`.
                          Spawns one \`git blame\` per file; scope it with
                          --blame-paths on a large tree.
  --blame-paths <globs>   Comma-separated globs limiting which files are blamed.
                          Implies --blame. Supports **, *, ?, {a,b} and [a-z].
  -h, --help              Show this message.

File discovery is \`git ls-files\`, so untracked build output is never counted.`;

function parseArgs(argv) {
  const opts = { json: false, blame: false, blamePaths: [], help: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--json') {
      opts.json = true;
    } else if (arg === '--markdown' || arg === '--md') {
      opts.json = false;
    } else if (arg === '--blame') {
      opts.blame = true;
    } else if (arg === '--blame-paths') {
      const value = argv[++i];
      if (value === undefined) fail('--blame-paths requires a glob argument');
      opts.blamePaths.push(...value.split(',').map((s) => s.trim()).filter(Boolean));
      opts.blame = true;
    } else if (arg.startsWith('--blame-paths=')) {
      const value = arg.slice('--blame-paths='.length);
      opts.blamePaths.push(...value.split(',').map((s) => s.trim()).filter(Boolean));
      opts.blame = true;
    } else if (arg === '-h' || arg === '--help') {
      opts.help = true;
    } else {
      fail(`unknown argument: ${arg}\n\n${HELP}`);
    }
  }
  return opts;
}

