/**
 * Print a message and exit with a non-zero status.
 *
 * The write is synchronous. `process.exit()` discards pending asynchronous
 * writes, and on POSIX a piped stderr — which is what continuous integration
 * hands this script — is asynchronous. The two messages that matter most here
 * are also the longest ones (the accounting self-check and the attribution
 * invariant, both of which list offending files), so an asynchronous write is
 * exactly where the explanation would be truncated or lost. `writeSync` can
 * still throw EAGAIN on a non-blocking pipe; fall back rather than exit mute.
 */
function fail(message, code = 2) {
  const text = `line-count: ${message}\n`;
  try {
    writeSync(2, text);
  } catch {
    process.stderr.write(text);
  }
  process.exit(code);
}

