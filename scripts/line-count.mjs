/** Does any path segment (excluding the basename) match the given set? */
function hasDirSegment(file, set) {
  const parts = file.split('/');
  for (let i = 0; i < parts.length - 1; i++) {
    if (set.has(parts[i])) return true;
  }
  return false;
}

/** The first excluded directory segment in a path, or null. */
function excludedSegment(file) {
  const parts = file.split('/');
  for (let i = 0; i < parts.length - 1; i++) {
    if (EXCLUDED_DIR_SEGMENTS.has(parts[i])) return parts[i];
  }
  return null;
}

/** Kind label plus the category the extension implies, for one file. */
function kindOf(file) {
  const basename = file.slice(file.lastIndexOf('/') + 1);
  const byBasename = BASENAME_KINDS.get(basename);
  if (byBasename) return { category: byBasename[0], kind: byBasename[1] };

  const ext = extensionOf(basename);

  // Config-shaped JSON is configuration; every other .json is data.
  if (ext === 'json') {
    if (
      JSON_CONFIG_BASENAMES.has(basename) ||
      /^tsconfig(\..+)?\.json$/.test(basename) ||
      /\.config\.json$/.test(basename)
    ) {
      return { category: 'Configuration', kind: 'JSON (config)' };
    }
  }

  // Dockerfile.web, Makefile.common, .env.example and friends.
  if (/^Dockerfile\./.test(basename)) return { category: 'Configuration', kind: 'Dockerfile' };
  if (/^Makefile\./.test(basename)) return { category: 'Configuration', kind: 'Makefile' };
  if (/^\.env(\..+)?$/.test(basename)) return { category: 'Configuration', kind: 'Environment file' };
  if (/^\.(eslintrc|prettierrc|babelrc|stylelintrc)(\..+)?$/.test(basename)) {
    return { category: 'Configuration', kind: 'Tooling config' };
  }
  if (/^(README|CHANGELOG|CONTRIBUTING|HANDOFF|ROADMAP|SECURITY|AGENTS)$/.test(basename)) {
    return { category: 'Documentation', kind: 'Plain text' };
  }

  const byExt = ext ? EXTENSION_KINDS.get(ext) : undefined;
  if (byExt) return { category: byExt[0], kind: byExt[1] };

  // Catch-all. The label keeps the extension so the row is actionable.
  return { category: 'Uncategorized', kind: ext ? `Other (.${ext})` : 'Other (no extension)' };
}

/** Does the opening of a text file declare that it is generated? */
function declaresGenerated(text) {
  const head = text.slice(0, 2048).split('\n').slice(0, 5).join('\n');
  return GENERATED_MARKERS.some((re) => re.test(head));
}

/**
 * Final category for a file. Generated wins over tests, tests win over the
 * extension's own category, so a generated fixture is never counted as
 * hand-written test code.
 */
function categoryOf(file, extensionCategory, isGeneratedByContent) {
  const basename = file.slice(file.lastIndexOf('/') + 1);
  if (
    isGeneratedByContent ||
    LOCKFILE_BASENAMES.has(basename) ||
    hasDirSegment(file, GENERATED_DIR_SEGMENTS)
  ) {
    return 'Generated';
  }
  if (
    hasDirSegment(file, TEST_DIR_SEGMENTS) ||
    /\.(test|spec)\.[^.]+$/.test(basename) ||
    /^(vitest|jest|playwright)\.config\.[^.]+$/.test(basename)
  ) {
    return 'Tests';
  }
  return extensionCategory;
}

/** Subproject label for a file, relative to its scope prefix. */
function areaOf(file, scopePrefix) {
  let rel = file;
  if (scopePrefix && rel.startsWith(scopePrefix)) rel = rel.slice(scopePrefix.length);
  const parts = rel.split('/');
  if (parts.length === 1) return '(root)';
  if (AREA_DEPTH_TWO.has(parts[0]) && parts.length > 2) return `${parts[0]}/${parts[1]}`;
  return parts[0];
}

