/** Format an integer with thousands separators, deterministically. */
function num(n) {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}

/** Share of a total, as a string. Returns '—' when the total is zero. */
function share(part, total) {
  if (!total) return '—';
  return `${((part / total) * 100).toFixed(1)}%`;
}

/** Lowercase extension without the dot, or '' when there is none. */
function extensionOf(basename) {
  const dot = basename.lastIndexOf('.');
  if (dot <= 0) return ''; // no dot, or a dotfile such as `.npmrc`
  return basename.slice(dot + 1).toLowerCase();
}

/**
 * Count lines the way `git blame` does: a trailing newline does not open a new
 * line, and an empty file has zero lines. Blank lines are lines that are empty
 * once whitespace (including a trailing CR) is removed.
 */
function countLines(text) {
  if (text === '') return { lines: 0, nonBlank: 0 };
  const parts = text.split('\n');
  if (parts[parts.length - 1] === '') parts.pop();
  let nonBlank = 0;
  for (const line of parts) {
    if (line.trim() !== '') nonBlank++;
  }
  return { lines: parts.length, nonBlank };
}

/**
 * Minimal glob → RegExp for `--blame-paths`. Supports `**`, `*`, `?`, `{a,b}` and
 * character classes. Anything else is matched literally.
 */
function globToRegExp(glob) {
  let out = '';
  let i = 0;
  const escape = (ch) => ch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  while (i < glob.length) {
    const ch = glob[i];
    if (ch === '*') {
      if (glob[i + 1] === '*') {
        if (glob[i + 2] === '/') {
          out += '(?:.*/)?';
          i += 3;
        } else {
          out += '.*';
          i += 2;
        }
        continue;
      }
      out += '[^/]*';
      i += 1;
      continue;
    }
    if (ch === '?') {
      out += '[^/]';
      i += 1;
      continue;
    }
    if (ch === '{') {
      const end = glob.indexOf('}', i);
      if (end !== -1) {
        const alts = glob
          .slice(i + 1, end)
          .split(',')
          .map((part) => part.split('').map(escape).join(''));
        out += `(?:${alts.join('|')})`;
        i = end + 1;
        continue;
      }
    }
    if (ch === '[') {
      const end = glob.indexOf(']', i + 1);
      if (end !== -1) {
        out += glob.slice(i, end + 1);
        i = end + 1;
        continue;
      }
    }
    out += escape(ch);
    i += 1;
  }
  return new RegExp(`^${out}$`);
}

/**
 * Build a path matcher from a list of globs. A pattern with no wildcard also
 * matches everything beneath it, so `--blame-paths scripts` scopes to that
 * directory as a reader would expect.
 */
function buildPathMatcher(globs) {
  if (globs.length === 0) return null;
  const matchers = globs.map((glob) => {
    const re = globToRegExp(glob);
    const plainPrefix = /[*?{[\]]/.test(glob) ? null : glob.replace(/\/+$/, '') + '/';
    return (file) => re.test(file) || (plainPrefix !== null && file.startsWith(plainPrefix));
  });
  return (file) => matchers.some((m) => m(file));
}

