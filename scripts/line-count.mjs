/** Sum a list of rows. */
function sum(rows) {
  return rows.reduce(
    (acc, row) => ({
      files: acc.files + row.files,
      lines: acc.lines + row.lines,
      nonBlank: acc.nonBlank + row.nonBlank,
    }),
    { files: 0, lines: 0, nonBlank: 0 },
  );
}

/** Category order first, then lines descending, then kind — stable across runs. */
function sortRows(rows) {
  return [...rows].sort((a, b) => {
    const ca = CATEGORY_ORDER.indexOf(a.category);
    const cb = CATEGORY_ORDER.indexOf(b.category);
    if (ca !== cb) return ca - cb;
    if (b.lines !== a.lines) return b.lines - a.lines;
    return a.kind.localeCompare(b.kind);
  });
}

/** Render a GitHub-flavoured Markdown table. */
function mdTable(headers, aligns, rows) {
  const sep = aligns.map((a) => (a === 'r' ? '---:' : a === 'c' ? ':---:' : '---'));
  const lines = [`| ${headers.join(' | ')} |`, `| ${sep.join(' | ')} |`];
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  return lines.join('\n');
}

function scopeTable(rows) {
  const sorted = sortRows(rows);
  const body = sorted.map((r) => [r.category, r.kind, num(r.files), num(r.lines), num(r.nonBlank)]);
  const total = sum(sorted);
  body.push(['**Total**', '', `**${num(total.files)}**`, `**${num(total.lines)}**`, `**${num(total.nonBlank)}**`]);
  return mdTable(['Category', 'Kind', 'Files', 'Lines', 'Non-blank'], ['l', 'l', 'r', 'r', 'r'], body);
}

function areaTable(rows) {
  const sorted = [...rows].sort((a, b) => (b.lines !== a.lines ? b.lines - a.lines : a.area.localeCompare(b.area)));
  const body = sorted.map((r) => [`\`${r.area}\``, num(r.files), num(r.lines), num(r.nonBlank)]);
  return mdTable(['Area', 'Files', 'Lines', 'Non-blank'], ['l', 'r', 'r', 'r'], body);
}

function renderMarkdown(report) {
  const out = [];
  const { scopes, excluded, totals, attribution, meta } = report;

  out.push('### Line count');
  out.push('');
  out.push(
    `Commit \`${meta.commitShort}\` · tracked files only (\`git ls-files\`), read from the working tree.`,
  );
  if (meta.workingTreeDirty) {
    out.push('');
    out.push(
      '> [!NOTE]',
      '> The working tree had uncommitted changes when this ran, so the counts describe the working tree rather than the commit alone.',
    );
  }
  out.push('');

  for (const scope of scopes) {
    out.push(`#### ${scope.label}`);
    out.push('');
    out.push(scopeTable(scope.rows));
    out.push('');
    if (scope.areas.length > 1) {
      out.push('<details>');
      out.push(`<summary>${scope.label} — the same lines split by subproject</summary>`);
      out.push('');
      out.push(areaTable(scope.areas));
      out.push('');
      out.push('</details>');
      out.push('');
    }
  }

  out.push('#### Excluded from the counts above');
  out.push('');
  if (excluded.length === 0) {
    out.push('No tracked file was excluded.');
  } else {
    const body = excluded.map((r) => [
      r.reason,
      num(r.files),
      r.linesKnown ? num(r.lines) : 'n/a',
      r.linesKnown ? num(r.nonBlank) : 'n/a',
      r.examples.map((e) => `\`${e}\``).join(', ') + (r.files > r.examples.length ? ', …' : ''),
    ]);
    out.push(mdTable(['Excluded', 'Files', 'Lines', 'Non-blank', 'Examples'], ['l', 'r', 'r', 'r', 'l'], body));
  }
  out.push('');

  out.push('#### Totals');
  out.push('');
  out.push(
    mdTable(
      ['Scope', 'Files', 'Lines', 'Non-blank'],
      ['l', 'r', 'r', 'r'],
      [
        [
          totals.own.label,
          num(totals.own.files),
          num(totals.own.lines),
          num(totals.own.nonBlank),
        ],
        [
          totals.grand.label,
          num(totals.grand.files),
          num(totals.grand.lines),
          num(totals.grand.nonBlank),
        ],
        [
          totals.everything.label,
          num(totals.everything.files),
          totals.everything.linesKnown ? num(totals.everything.lines) : `${num(totals.everything.lines)} (text rows only)`,
          totals.everything.linesKnown
            ? num(totals.everything.nonBlank)
            : `${num(totals.everything.nonBlank)} (text rows only)`,
        ],
      ],
    ),
  );
  out.push('');

  out.push('#### Authorship — surviving lines');
  out.push('');
  out.push(
    'Attributed per surviving line with `git blame`, not by summing added lines from the log: a line written and later deleted belongs to nobody.',
  );
  out.push('');
  out.push(
    `Rule used: a commit counts as **agent-authored** when its author name or email matches \`${AGENT_IDENTITY_RE.source}\` (case-insensitive), ` +
      'or when its message carries a `Co-Authored-By:` trailer whose value matches the same pattern. Every other commit counts as human-authored. ' +
      'Lines present in the working tree but not yet committed are reported on their own row.',
  );
  out.push('');
  if (!attribution.computed) {
    out.push(
      mdTable(
        ['Authorship', 'Lines', 'Share'],
        ['l', 'r', 'r'],
        [['Agent-authored', 'not computed', '—'], ['Human-authored', 'not computed', '—']],
      ),
    );
    out.push('');
    out.push('Re-run with `--blame` (optionally `--blame-paths <globs>`) to compute it.');
  } else {
    const rows = [
      ['Agent-authored', num(attribution.agent), share(attribution.agent, attribution.lines)],
      ['Human-authored', num(attribution.human), share(attribution.human, attribution.lines)],
    ];
    if (attribution.uncommitted > 0) {
      rows.push([
        'Uncommitted (working tree)',
        num(attribution.uncommitted),
        share(attribution.uncommitted, attribution.lines),
      ]);
    }
    if (attribution.unclassified > 0) {
      rows.push([
        'Unclassified commit',
        num(attribution.unclassified),
        share(attribution.unclassified, attribution.lines),
      ]);
    }
    rows.push([
      '**Total attributed**',
      `**${num(attribution.lines)}**`,
      `**${share(attribution.lines, attribution.lines)}**`,
    ]);
    out.push(mdTable(['Authorship', 'Lines', 'Share'], ['l', 'r', 'r'], rows));
    out.push('');
    out.push(
      `Scope: ${attribution.scope} — ${num(attribution.files)} file(s). The attributed total equals the counted line total for that same scope.`,
    );
  }
  out.push('');

  out.push('#### Reproduce');
  out.push('');
  out.push('```');
  out.push(meta.command);
  out.push('```');
  out.push('');
  out.push(
    'Counts every tracked file exactly once: each scope table sums to its own total, and every excluded path is a visible row above.',
  );
  if (report.uncategorized.length > 0) {
    out.push('');
    out.push(
      `${num(report.uncategorized.length)} file(s) landed in the catch-all \`Uncategorized\` row; run with \`--json\` to list them.`,
    );
  }
  return out.join('\n');
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  const argv = process.argv.slice(2);
  const opts = parseArgs(argv);
  if (opts.help) {
    process.stdout.write(`${HELP}\n`);
    return;
  }

  let repoRoot;
  try {
    repoRoot = git(['rev-parse', '--show-toplevel'], { cwd: process.cwd() }).trim();
  } catch {
    fail('not inside a git repository (git rev-parse --show-toplevel failed)');
  }

  let scriptRel = SCRIPT_REL_FALLBACK;
  try {
    scriptRel = path.relative(repoRoot, fileURLToPath(import.meta.url)).split(path.sep).join('/');
  } catch {
    // Keep the fallback; the reproduce line stays correct for a repo-root run.
  }
  const command = ['node', scriptRel, ...argv].join(' ');

  let commit = '';
  let commitShort = '';
  try {
    commit = git(['rev-parse', 'HEAD'], { cwd: repoRoot }).trim();
    commitShort = commit.slice(0, 7);
  } catch {
    commit = '';
    commitShort = '(no commit yet)';
  }
  let workingTreeDirty = false;
  try {
    workingTreeDirty = git(['status', '--porcelain'], { cwd: repoRoot }).trim().length > 0;
  } catch {
    workingTreeDirty = false;
  }

  const entries = listTrackedFiles(repoRoot);
  const { rows, areas, excluded, counted, uncategorizedPaths } = collect(repoRoot, entries);

  // Self-check: every tracked file is either a counted row or an excluded row.
  const countedFiles = sum(rows).files;
  const excludedFiles = excluded.reduce((n, r) => n + r.files, 0);
  if (countedFiles + excludedFiles !== entries.length) {
    fail(
      `internal accounting error: ${num(entries.length)} tracked file(s) but ${num(countedFiles)} counted + ` +
        `${num(excludedFiles)} excluded = ${num(countedFiles + excludedFiles)}. A bucketing that loses files is a misrepresentation; ` +
        'fix the classifier rather than publishing the number.',
      1,
    );
  }

  // Build the reported scopes: this repository's own code first, then each
  // imported upstream tree.
  const scopes = [];
  const ownRows = rows.filter((r) => r.scope === '');
  scopes.push({
    key: 'own',
    prefix: '',
    label: "This repository's own code",
    rows: ownRows,
    areas: areas.filter((a) => a.scope === ''),
    totals: sum(ownRows),
  });
  for (const upstream of UPSTREAM_PREFIXES) {
    const scopeRows = rows.filter((r) => r.scope === upstream.prefix);
    if (scopeRows.length === 0) continue;
    scopes.push({
      key: upstream.prefix,
      prefix: upstream.prefix,
      label: upstream.label,
      rows: scopeRows,
      areas: areas.filter((a) => a.scope === upstream.prefix),
      totals: sum(scopeRows),
    });
  }

  // Every scope table carries the mandatory catch-all row, even at zero, so a
  // reader can see that nothing was dropped.
  for (const scope of scopes) {
    if (!scope.rows.some((r) => r.category === 'Uncategorized')) {
      scope.rows.push({ scope: scope.prefix, category: 'Uncategorized', kind: '—', files: 0, lines: 0, nonBlank: 0 });
    }
  }

  const grand = sum(rows);
  const own = sum(ownRows);
  const excludedKnown = excluded.filter((r) => r.linesKnown);
  const excludedLines = excludedKnown.reduce((n, r) => n + r.lines, 0);
  const excludedNonBlank = excludedKnown.reduce((n, r) => n + r.nonBlank, 0);

  const totals = {
    own: {
      label: "Project's own code (everything tracked outside the imported upstream tree)",
      files: own.files,
      lines: own.lines,
      nonBlank: own.nonBlank,
    },
    grand: {
      label: 'Grand total counted (own code + imported upstream tree)',
      files: grand.files,
      lines: grand.lines,
      nonBlank: grand.nonBlank,
    },
    everything: {
      label: 'All tracked files, including the excluded rows above',
      files: grand.files + excludedFiles,
      lines: grand.lines + excludedLines,
      nonBlank: grand.nonBlank + excludedNonBlank,
      // Binary, symlink and gitlink rows have no line count, so the figure covers
      // the text rows only. Said plainly rather than implied.
      linesKnown: excluded.every((r) => r.linesKnown),
    },
  };

  let attribution = { computed: false };
  if (opts.blame) {
    const matcher = buildPathMatcher(opts.blamePaths);
    attribution = attribute(repoRoot, counted, matcher);
  }

  const report = {
    meta: {
      command,
      commit,
      commitShort,
      workingTreeDirty,
      trackedFiles: entries.length,
      discovery: 'git ls-files',
    },
    scopes: scopes.map((s) => ({
      key: s.key,
      label: s.label,
      prefix: s.prefix,
      rows: sortRows(s.rows).map((r) => ({
        category: r.category,
        kind: r.kind,
        files: r.files,
        lines: r.lines,
        nonBlank: r.nonBlank,
      })),
      areas: [...s.areas]
        .sort((a, b) => (b.lines !== a.lines ? b.lines - a.lines : a.area.localeCompare(b.area)))
        .map((a) => ({ area: a.area, files: a.files, lines: a.lines, nonBlank: a.nonBlank })),
      total: sum(s.rows),
    })),
    excluded: excluded
      .map((r) => ({
        reason: r.reason,
        files: r.files,
        lines: r.linesKnown ? r.lines : null,
        nonBlank: r.linesKnown ? r.nonBlank : null,
        linesKnown: r.linesKnown,
        examples: r.examples,
      }))
      .sort((a, b) => b.files - a.files),
    totals,
    attribution: {
      ...attribution,
      rule:
        'agent-authored when the commit author name or email matches the automation pattern, or the commit message carries a ' +
        'Co-Authored-By trailer naming an agent; every other commit is human-authored',
      pattern: AGENT_IDENTITY_RE.source,
    },
    uncategorized: uncategorizedPaths,
  };

  if (opts.json) {
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  } else {
    process.stdout.write(`${renderMarkdown(report)}\n`);
  }
}

try {
  main();
} catch (err) {
  fail(err && err.stack ? err.stack : String(err), 1);
}
