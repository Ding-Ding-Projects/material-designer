/**
 * Classify a commit as agent- or human-authored. The result is cached because a
 * blame run over a large tree revisits the same commits thousands of times.
 */
function makeCommitClassifier(repoRoot) {
  const cache = new Map();
  return function classify(sha) {
    if (cache.has(sha)) return cache.get(sha);
    let out;
    try {
      out = git(['show', '-s', '--no-patch', '--format=%an%x00%ae%x00%B', sha], { cwd: repoRoot });
    } catch {
      // A commit that cannot be read is reported as unclassified rather than
      // guessed at; the caller surfaces the count.
      const unknown = { agent: false, unclassified: true, reason: 'commit could not be read' };
      cache.set(sha, unknown);
      return unknown;
    }
    const [name = '', email = '', body = ''] = out.split('\u0000');
    let agent = AGENT_IDENTITY_RE.test(name) || AGENT_IDENTITY_RE.test(email);
    let reason = agent ? 'author identity matches the automation pattern' : '';
    if (!agent) {
      COAUTHOR_TRAILER_RE.lastIndex = 0;
      let match;
      while ((match = COAUTHOR_TRAILER_RE.exec(body)) !== null) {
        if (AGENT_IDENTITY_RE.test(match[1])) {
          agent = true;
          reason = 'Co-Authored-By trailer names an agent';
          break;
        }
      }
    }
    const result = { agent, unclassified: false, reason: reason || 'no automation signal' };
    cache.set(sha, result);
    return result;
  };
}

/**
 * Sum blamed lines per commit for one file, using `git blame --incremental`
 * (header blocks are emitted once per commit; every group carries its line count).
 */
function blameFile(repoRoot, file) {
  const out = git(['blame', '--incremental', '--', file], { cwd: repoRoot });
  const perSha = new Map();
  let total = 0;
  for (const line of out.split('\n')) {
    // `\r?` because git on some platforms terminates lines with CRLF.
    const m = /^([0-9a-f]{40,64}) \d+ \d+ (\d+)\r?$/.exec(line);
    if (!m) continue;
    const sha = m[1];
    const n = Number(m[2]);
    perSha.set(sha, (perSha.get(sha) ?? 0) + n);
    total += n;
  }
  return { perSha, total };
}

/**
 * Attribute every surviving line in scope. Fails loudly if the attribution total
 * and the counted line total disagree — two contradictory numbers in one table
 * destroy the credibility of both.
 */
function attribute(repoRoot, counted, matcher) {
  const files = counted.filter((f) => (matcher ? matcher(f.path) : true));
  const classify = makeCommitClassifier(repoRoot);
  const totals = { agent: 0, human: 0, uncommitted: 0, unclassified: 0 };
  const mismatches = [];
  const failures = [];
  let attributedTotal = 0;
  let countedTotal = 0;
  let done = 0;
  const isTty = Boolean(process.stderr.isTTY);
  let lastTick = 0;

  process.stderr.write(
    `line-count: attributing ${num(files.length)} file(s) with git blame; this spawns one blame per file\n`,
  );

  for (const record of files) {
    countedTotal += record.lines;
    if (record.lines > 0) {
      let result;
      try {
        result = blameFile(repoRoot, record.path);
      } catch (err) {
        failures.push(`${record.path}: ${err && err.message ? err.message.split('\n')[0] : String(err)}`);
        done++;
        continue;
      }
      if (result.total !== record.lines) {
        mismatches.push(`${record.path}: counted ${record.lines}, blamed ${result.total}`);
      }
      attributedTotal += result.total;
      for (const [sha, n] of result.perSha) {
        if (UNCOMMITTED_SHA_RE.test(sha)) {
          totals.uncommitted += n;
          continue;
        }
        const info = classify(sha);
        if (info.unclassified) totals.unclassified += n;
        else if (info.agent) totals.agent += n;
        else totals.human += n;
      }
    }
    done++;
    const now = Date.now();
    if (now - lastTick > 500 || done === files.length) {
      lastTick = now;
      const message = `line-count: blame ${num(done)}/${num(files.length)} files`;
      if (isTty) process.stderr.write(`\r${message}   `);
      else if (done % 250 === 0 || done === files.length) process.stderr.write(`${message}\n`);
    }
  }
  if (isTty) process.stderr.write('\n');

  if (failures.length) {
    fail(
      `git blame failed on ${failures.length} file(s); attribution is incomplete and is not reported.\n  ` +
        failures.slice(0, 10).join('\n  '),
      1,
    );
  }
  if (attributedTotal !== countedTotal) {
    fail(
      `attribution total (${num(attributedTotal)}) does not equal the counted line total for the same scope ` +
        `(${num(countedTotal)}).\n` +
        `The usual cause is counting a file's trailing newline as an extra line, which git blame does not.\n` +
        `First mismatching files:\n  ${
          mismatches.length ? mismatches.slice(0, 10).join('\n  ') : '(no per-file mismatch was recorded)'
        }`,
      1,
    );
  }

  return {
    computed: true,
    scope: matcher ? 'files matching --blame-paths' : 'every counted file',
    files: files.length,
    lines: attributedTotal,
    agent: totals.agent,
    human: totals.human,
    uncommitted: totals.uncommitted,
    unclassified: totals.unclassified,
  };
}

