#!/usr/bin/env node
/**
 * scripts/line-count.mjs — the committed line counter for this repository.
 *
 * This is the script CI runs at the released commit; its table is what goes into
 * the release notes. It exists so the figure is produced the same way every time,
 * by a program anyone can read, rather than by a hand-typed number that drifts.
 *
 * Design rules this script follows:
 *
 *   - File discovery is `git ls-files`, so untracked build output can never be
 *     counted. Nothing is discovered by walking the filesystem.
 *   - Every tracked file lands in exactly one row. There is a mandatory
 *     "Uncategorized" catch-all in each scope, and a self-check that the rows sum
 *     back to the tracked-file count. A bucketing that loses files misrepresents
 *     the project.
 *   - Excluded paths are printed as visible rows with their own numbers, never
 *     silently dropped.
 *   - The imported upstream tree (`design/`) is reported separately from this
 *     repository's own code, and the totals are labelled so a reader can see both
 *     what the project is and what the repository holds.
 *   - Authorship is attributed per SURVIVING line with `git blame`, never by
 *     summing added lines from the log. It is opt-in behind `--blame` because it
 *     spawns one `git blame` per file.
 *   - The attribution total must equal the counted line total for the same scope.
 *     If they disagree the script fails loudly instead of printing two numbers
 *     that contradict each other.
 *
 * No dependencies outside node: builtins. Node ESM.
 *
 * Usage:
 *   node scripts/line-count.mjs
 *   node scripts/line-count.mjs --json
 *   node scripts/line-count.mjs --blame
 *   node scripts/line-count.mjs --blame --blame-paths 'scripts/**,mockups/**'
 */

